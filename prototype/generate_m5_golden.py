import numpy as np

def generate_golden_header(output_path):
    np.random.seed(1337)
    num_vectors = 100
    dim = 64
    num_queries = 5
    top_k = 5

    # Generate random vectors on unit sphere
    vectors = np.random.randn(num_vectors, dim).astype(np.float32)
    vectors /= np.linalg.norm(vectors, axis=1, keepdims=True)

    queries = np.random.randn(num_queries, dim).astype(np.float32)
    queries /= np.linalg.norm(queries, axis=1, keepdims=True)

    # Compute cosine similarity (dot product of unit vectors)
    # scores shape: (num_queries, num_vectors)
    scores = np.dot(queries, vectors.T)

    with open(output_path, "w") as f:
        f.write("// Auto-generated by prototype/generate_m5_golden.py using NumPy\n")
        f.write("#pragma once\n\n")
        f.write("#include <cstddef>\n")
        f.write("#include <cstdint>\n\n")
        f.write("namespace purpledb {\nnamespace test {\n\n")
        f.write(f"constexpr size_t kGoldenNumVectors = {num_vectors};\n")
        f.write(f"constexpr size_t kGoldenDim = {dim};\n")
        f.write(f"constexpr size_t kGoldenNumQueries = {num_queries};\n")
        f.write(f"constexpr size_t kGoldenTopK = {top_k};\n\n")

        # Write vectors
        f.write("static const float kGoldenVectors[kGoldenNumVectors * kGoldenDim] = {\n")
        flat_vecs = vectors.flatten()
        for i, val in enumerate(flat_vecs):
            f.write(f"{val:.8f}f, ")
            if (i + 1) % 8 == 0:
                f.write("\n")
        f.write("};\n\n")

        # Write queries
        f.write("static const float kGoldenQueries[kGoldenNumQueries * kGoldenDim] = {\n")
        flat_queries = queries.flatten()
        for i, val in enumerate(flat_queries):
            f.write(f"{val:.8f}f, ")
            if (i + 1) % 8 == 0:
                f.write("\n")
        f.write("};\n\n")

        # Write NumPy reference top-K results
        f.write("struct GoldenQueryResult {\n  uint64_t expected_id;\n  float expected_score;\n};\n\n")
        f.write("static const GoldenQueryResult kGoldenExpected[kGoldenNumQueries][kGoldenTopK] = {\n")
        for q_idx in range(num_queries):
            q_scores = scores[q_idx]
            top_indices = np.argsort(-q_scores)[:top_k]
            f.write("  {\n")
            for idx in top_indices:
                score = q_scores[idx]
                f.write(f"    {{{idx}ULL, {score:.8f}f}},\n")
            f.write("  },\n")
        f.write("};\n\n")
        f.write("}  // namespace test\n}  // namespace purpledb\n")

if __name__ == "__main__":
    generate_golden_header("tests/m5_numpy_golden.h")
    print("Generated tests/m5_numpy_golden.h successfully.")

