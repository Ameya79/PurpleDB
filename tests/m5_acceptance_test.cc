class M5AcceptanceTest {
 public:
  M5AcceptanceTest() : env_(Env::Default()) {
    test_dir_ = "./m5_acceptance_db";
    env_->CreateDir(test_dir_);
  }

  ~M5AcceptanceTest() {
    std::vector<std::string> children;
    env_->GetChildren(test_dir_, &children);
    for (const auto& f : children) {
      if (f != "." && f != "..") {
        std::string path = test_dir_ + "/" + f;
        std::vector<std::string> sub_children;
        if (env_->GetChildren(path, &sub_children).ok()) {
          for (const auto& sf : sub_children) {
            if (sf != "." && sf != "..") {
              env_->DeleteFile(path + "/" + sf);
            }
          }
          env_->DeleteDir(path);
        } else {
          env_->DeleteFile(path);
        }
      }
    }
    env_->DeleteDir(test_dir_);
  }

  Env* env_;
  std::string test_dir_;
};

/**
 * ACCEPTANCE CRITERIA 1: Exact results match a NumPy reference.
 * Loads 100 64-dimensional unit vectors and queries generated by NumPy.
 * Verifies that PurpleDB's SIMD brute-force cosine search produces the
 * exact same top-K vector IDs and similarity scores (recall@5 = 100%).
 */
TEST(M5AcceptanceTest, ExactResultsMatchNumPyReference) {
  M5AcceptanceTest fixture;
  VectorOptions options;
  options.dim = static_cast<uint32_t>(kGoldenDim);
  options.chunk_size = 16;
  options.metric = MetricType::kCosine;
  options.model_id = "numpy-reference-model";

  std::unique_ptr<VectorIndex> index;
  Status s = VectorIndex::Open(options, fixture.test_dir_, &index);
  ASSERT_STATUS_OK(s);

  // Ingest all golden vectors
  for (size_t i = 0; i < kGoldenNumVectors; ++i) {
    const float* vec_ptr = kGoldenVectors + i * kGoldenDim;
    std::string key = "moment_" + std::to_string(i);
    s = index->Put(key, vec_ptr, kGoldenDim);
    ASSERT_STATUS_OK(s);
  }
  ASSERT_EQ(index->Count(), kGoldenNumVectors);

  // Run all queries and compare against NumPy reference
  size_t total_correct = 0;
  size_t total_tested = kGoldenNumQueries * kGoldenTopK;

  for (size_t q = 0; q < kGoldenNumQueries; ++q) {
    const float* query_ptr = kGoldenQueries + q * kGoldenDim;
    std::vector<SearchResult> results;
    s = index->Search(query_ptr, kGoldenDim, kGoldenTopK, &results);
    ASSERT_STATUS_OK(s);
    ASSERT_EQ(results.size(), kGoldenTopK);

    for (size_t k = 0; k < kGoldenTopK; ++k) {
      uint64_t expected_id = kGoldenExpected[q][k].expected_id;
      float expected_score = kGoldenExpected[q][k].expected_score;
      std::string expected_key = "moment_" + std::to_string(expected_id);

      ASSERT_EQ(results[k].key, expected_key);
      ASSERT_NEAR(results[k].score, expected_score, 1e-4f);
      total_correct++;
    }
  }

  double recall = static_cast<double>(total_correct) / static_cast<double>(total_tested);
  ASSERT_NEAR(recall, 1.0, 1e-6);
}

/**
 * ACCEPTANCE CRITERIA 2: Crash tests cover vector writes.
 * Injects faults and torn tails into .vec files at arbitrary byte offsets.
 * Verifies recovery preserves all durable chunks and ignores corrupted tails.
 */
TEST(M5AcceptanceTest, CrashTestsCoverVectorWrites) {
  M5AcceptanceTest fixture;
  VectorOptions options;
  options.dim = 16;
  options.chunk_size = 8;
  options.metric = MetricType::kCosine;

  // Perform truncation crash tests at 5 different offsets
  std::vector<size_t> truncate_cuts = {1, 3, 4, 17, 33};
  for (size_t test_idx = 0; test_idx < truncate_cuts.size(); ++test_idx) {
    std::string sub_dir = fixture.test_dir_ + "/crash_" + std::to_string(test_idx);
    fixture.env_->CreateDir(sub_dir);

    // 1. Populate database with 40 vectors (5 full chunks of 8 vectors)
    {
      std::unique_ptr<VectorIndex> index;
      Status s = VectorIndex::Open(options, sub_dir, &index);
      ASSERT_STATUS_OK(s);

      std::vector<float> vec(16, 0.25f);
      for (size_t i = 0; i < 40; ++i) {
        vec[0] = static_cast<float>(i);
        NormalizeVector(vec.data(), 16);
        s = index->Put("vid_" + std::to_string(i), vec.data(), 16);
        ASSERT_STATUS_OK(s);
      }
      index->Sync();
    }

    std::string vec_file = sub_dir + "/000001.vec";
    uint64_t original_size = 0;
    fixture.env_->GetFileSize(vec_file, &original_size);
    ASSERT_GT(original_size, 0u);

    // Read full content into buffer
    std::string file_content;
    {
      std::unique_ptr<SequentialFile> sf;
      fixture.env_->NewSequentialFile(vec_file, &sf);
      char buf[8192];
      Slice sl;
      sf->Read(original_size, &sl, buf);
      file_content = std::string(sl.data(), sl.size());
    }

    // Truncate .vec file by cut bytes
    size_t cut = truncate_cuts[test_idx];
    if (cut < original_size) {
      size_t truncated_len = original_size - cut;
      {
        std::unique_ptr<WritableFile> wf;
        fixture.env_->NewWritableFile(vec_file, &wf);
        wf->Append(Slice(file_content.data(), truncated_len));
        wf->Close();
      }
    }

    // Reopen index: must recover gracefully without crashing
    std::unique_ptr<VectorIndex> recovered_index;
    Status s = VectorIndex::Open(options, sub_dir, &recovered_index);
    ASSERT_STATUS_OK(s);

    // Number of recovered vectors should be bounded by valid chunks (<= 40)
    ASSERT_LE(recovered_index->Count(), 40u);

    // New writes after recovery must succeed cleanly
    std::vector<float> new_vec(16, 0.5f);
    NormalizeVector(new_vec.data(), 16);
    s = recovered_index->Put("post_crash_key", new_vec.data(), 16);
    ASSERT_STATUS_OK(s);
    ASSERT_TRUE(recovered_index->Contains("post_crash_key"));
  }
}

/**
 * ACCEPTANCE CRITERIA: Delete bitmap tombstoning and search filtering.
 */
TEST(M5AcceptanceTest, DeleteBitmapHidesTombstonedVectors) {
  M5AcceptanceTest fixture;
  VectorOptions options;
  options.dim = 8;
  options.metric = MetricType::kCosine;

  std::unique_ptr<VectorIndex> index;
  Status s = VectorIndex::Open(options, fixture.test_dir_, &index);
  ASSERT_STATUS_OK(s);

  // Insert 20 vectors
  for (size_t i = 0; i < 20; ++i) {
    std::vector<float> vec(8, 0.1f);
    vec[i % 8] = 1.0f;
    NormalizeVector(vec.data(), 8);
    index->Put("k_" + std::to_string(i), vec.data(), 8);
  }
  ASSERT_EQ(index->Count(), 20u);

  // Delete 10 vectors
  for (size_t i = 0; i < 10; ++i) {
    s = index->Delete("k_" + std::to_string(i));
    ASSERT_STATUS_OK(s);
  }
  ASSERT_EQ(index->Count(), 10u);
  ASSERT_NEAR(index->DeletedFraction(), 0.5, 1e-4);

  // Search top-15: only 10 active items can ever be returned
  std::vector<float> query(8, 0.1f);
  query[0] = 1.0f;
  NormalizeVector(query.data(), 8);

  std::vector<SearchResult> results;
  s = index->Search(query.data(), 8, 15, &results);
  ASSERT_STATUS_OK(s);
  ASSERT_EQ(results.size(), 10u);

  // Verify none of the deleted keys (k_0 .. k_9) appear
  for (const auto& r : results) {
    for (size_t d = 0; d < 10; ++d) {
      ASSERT_NE(r.key, "k_" + std::to_string(d));
    }
  }
}

